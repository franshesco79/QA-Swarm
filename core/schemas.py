"""
Pydantic v2 schemas for QA-Swarm.
Defines core data structures for visual defects, root-cause analysis,
code patches, chaos test cases, and aggregate audit reports.
"""

from typing import List, TypeAlias
from pydantic import BaseModel, ConfigDict, Field, field_validator


class VisualDefect(BaseModel):
    """
    Represents a visual anomaly detected in the UI.
    bbox follows the normalized/standard ordering [ymin, xmin, ymax, xmax].
    """
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    element_name: str = Field(..., description="Name or identifier of the UI component")
    bbox: List[float] = Field(
        ...,
        description="Bounding box coordinates in [ymin, xmin, ymax, xmax] format"
    )
    defect_type: str = Field(
        default="LAYOUT_OVERFLOW",
        description="Type of defect (e.g. LAYOUT_OVERFLOW, TEXT_CLIPPING, COLOR_CONTRAST)"
    )
    severity: str = Field(
        default="WARNING",
        description="Severity level (e.g. LOW, WARNING, HIGH, CRITICAL)"
    )

    @field_validator("bbox")
    @classmethod
    def validate_bbox(cls, v: List[float]) -> List[float]:
        if len(v) != 4:
            raise ValueError("bbox must contain exactly 4 coordinates: [ymin, xmin, ymax, xmax]")
        ymin, xmin, ymax, xmax = v
        if ymin > ymax:
            raise ValueError(f"ymin ({ymin}) must be <= ymax ({ymax})")
        if xmin > xmax:
            raise ValueError(f"xmin ({xmin}) must be <= xmax ({xmax})")
        return [float(x) for x in v]


class RootCauseLink(BaseModel):
    """
    Associates an observed defect to the code-level source location and offending token.
    """
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    target_file: str = Field(..., description="Path to the offending source file")
    target_line: int = Field(..., ge=1, description="1-indexed line number in target file")
    offending_token: str = Field(..., description="Specific code snippet or token causing the issue")
    explanation: str = Field(..., description="Technical explanation of the defect causation")


class CodePatch(BaseModel):
    """
    Represents an automated or suggested remediation patch for an identified defect.
    """
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    target_file: str = Field(..., description="Target source file to apply remediation")
    target_line: int = Field(..., ge=1, description="Line number where patch should be applied")
    original_snippet: str = Field(..., description="Original code snippet to be replaced")
    replacement_snippet: str = Field(..., description="Replacement snippet addressing the defect")


class ChaosTestCase(BaseModel):
    """
    Scenario generated by the Chaos Engine to stress-test the UI/backend resilience.
    """
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    test_id: str = Field(..., description="Unique identifier for chaos test scenario")
    input_payload: str = Field(..., description="Input payload or stimulus applied")
    stress_vector: str = Field(..., description="Stress vector category (e.g. LATENCY, CONCURRENCY, EXTREME_INPUT)")
    expected_behavior: str = Field(..., description="Expected system response under stress")


class QAAuditReport(BaseModel):
    """
    Comprehensive audit report generated by QA-Swarm for automated QA & CI/CD gates.
    """
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    health_score: int = Field(..., ge=0, le=100, description="Overall health score between 0 and 100")
    verdict: str = Field(..., description="Verdict status: PASS, WARN, or BLOCK_DEPLOYMENT")
    defects: List[VisualDefect] = Field(default_factory=list, description="List of visual defects found")
    root_causes: List[RootCauseLink] = Field(default_factory=list, description="Mapped root causes")
    patches: List[CodePatch] = Field(default_factory=list, description="Remediation code patches")
    chaos_suite: List[ChaosTestCase] = Field(default_factory=list, description="Chaos resilience test suite")


# Type alias conforming to SwarmAuditResult specification
SwarmAuditResult: TypeAlias = QAAuditReport

__all__ = [
    "VisualDefect",
    "RootCauseLink",
    "CodePatch",
    "ChaosTestCase",
    "QAAuditReport",
    "SwarmAuditResult",
]
