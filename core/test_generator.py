"""
Playwright Regression Test Generator and AST Validator for QA-Swarm.
Generates synchronous Playwright regression tests validating visual/layout defect remediation,
geometric bounds, and defensive DOM interactions.
"""

import ast
import logging
from pathlib import Path
import re

from core.schemas import CodePatch, VisualDefect

logger = logging.getLogger("qa_swarm.test_generator")

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_TEST_OUTPUT = PROJECT_ROOT / "test_samples" / "test_regression.py"


def generate_playwright_test(
    defect: VisualDefect,
    patch: CodePatch,
    target_url: str = "http://localhost:8501",
    mock: bool = True,
) -> str:
    """
    Synthesizes an executable Python regression test using Playwright's sync API.
    Verifies element visibility, geometric bounding boxes, parent container overflow
    (scrollWidth <= clientWidth), and defensive interaction safety.
    """
    clean_identifier = re.sub(r"\W+", "_", defect.element_name).strip("_") or "target_element"
    selector = f"#{defect.element_name}" if not defect.element_name.startswith("#") else defect.element_name

    test_script = f'''"""
Automated Playwright Regression Test generated by QA-Swarm.
Validates remediation of defect on element '{defect.element_name}' ({defect.defect_type}).
Patched file: {patch.target_file}:{patch.target_line}
"""

import sys
from playwright.sync_api import sync_playwright, expect


def test_regression_{clean_identifier}():
    """
    Regression test ensuring '{defect.element_name}' is rendered properly
    without layout overflow and handles interactions defensively.
    """
    target_url = "{target_url}"
    element_selector = "{selector}"

    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        context = browser.new_context(viewport={{"width": 1280, "height": 720}})
        page = context.new_page()

        try:
            page.goto(target_url, timeout=15000)

            # 1. Locate and assert visibility of target element
            locator = page.locator(element_selector)
            if locator.count() == 0:
                locator = page.locator(f"[id='{defect.element_name}'], button:has-text('Checkout'), text='{defect.element_name}'").first

            expect(locator).to_be_visible()

            # 2. Geometric DOM verification
            box = locator.bounding_box()
            assert box is not None, "Target element bounding_box must not be None"
            assert box["width"] > 0, "Element width must be strictly positive"
            assert box["height"] > 0, "Element height must be strictly positive"

            # 3. Verify no layout overflow relative to parent container
            is_overflowing = page.evaluate(
                """(sel) => {{
                    const el = document.querySelector(sel);
                    if (!el) return false;
                    const parent = el.parentElement;
                    if (!parent) return false;
                    return parent.scrollWidth > parent.clientWidth;
                }}""",
                element_selector,
            )
            assert not is_overflowing, "Component container must satisfy scrollWidth <= clientWidth"

            # 4. Defensive interaction test
            locator.click(timeout=5000)

        finally:
            context.close()
            browser.close()


if __name__ == "__main__":
    test_regression_{clean_identifier}()
    print("Playwright regression test passed with 0 errors.")
'''
    return test_script


def validate_test_syntax(test_code: str) -> bool:
    """
    Uses Python's built-in AST parser to mathematically verify that the generated
    test code is 100% syntactically valid Python.
    """
    try:
        ast.parse(test_code)
        return True
    except (SyntaxError, ValueError):
        return False


def save_generated_test(
    test_code: str,
    output_path: str = "test_samples/test_regression.py",
) -> str:
    """
    Validates script syntax and safely writes the generated Playwright regression test
    to disk, returning its absolute path.
    """
    if not validate_test_syntax(test_code):
        raise ValueError("Invalid Python syntax detected in generated test code")

    resolved_path = Path(output_path).resolve()
    resolved_path.parent.mkdir(parents=True, exist_ok=True)

    with open(resolved_path, "w", encoding="utf-8") as f:
        f.write(test_code)

    return str(resolved_path)
